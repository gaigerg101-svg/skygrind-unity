#!/usr/bin/env python3
# NIGHT27 builder B: writes Design/maps/lantern-arena.json, THE LANTERN's ring courtyard (axis-aligned boxes only: the C# collider's kind).
# A square courtyard 32 m across inside (|x|, |z| < 16), 12 m high, a floor, a roof with a skylight slot over the middle (25 % of the floor),
# and a RING of eight wall-ride segments (1 m slabs on the inner faces, kind "seg0".."seg7": sector i holds directions [i*45, (i+1)*45) degrees of
# atan2(z, x) around the lantern, the sim's Lantern27.SegmentAt). Behind the slabs a 2 m shell (kind "wall") so a segment that retracts leaves a recess,
# never the outside. ARENA-LOCAL coordinates (centre 0, 0, 0). Run from the repo root: python Tools/night/gen-lantern.py
import json

R = 16.0   # inner half-width
T = 1.0    # slab thickness
S = 2.0    # shell thickness
H = 12.0   # wall height
boxes = []


def box(x0, y0, z0, x1, y1, z1, kind):
    boxes.append({"min": [x0, y0, z0], "max": [x1, y1, z1], "kind": kind})


O = R + T + S  # outer edge
box(-O, -0.5, -O, O, 0, O, "floor")
# shell (behind the slabs) and corner pillars
box(R + T, 0, -O, O, H, O, "wall")
box(-O, 0, -O, -(R + T), H, O, "wall")
box(-(R + T), 0, R + T, R + T, H, O, "wall")
box(-(R + T), 0, -O, R + T, H, -(R + T), "wall")
for sx in (-1, 1):
    for sz in (-1, 1):
        x0, x1 = sorted((sx * R, sx * (R + T)))
        z0, z1 = sorted((sz * R, sz * (R + T)))
        box(x0, 0, z0, x1, H, z1, "wall")
# the eight segments (sector i: direction [i*45, (i+1)*45) deg of atan2(z, x))
box(R, 0, -R, R + T, H, 0, "seg7")
box(R, 0, 0, R + T, H, R, "seg0")
box(0, 0, R, R, H, R + T, "seg1")
box(-R, 0, R, 0, H, R + T, "seg2")
box(-(R + T), 0, 0, -R, H, R, "seg3")
box(-(R + T), 0, -R, -R, H, 0, "seg4")
box(-R, 0, -(R + T), 0, H, -R, "seg5")
box(0, 0, -(R + T), R, H, -R, "seg6")
# the roof with a skylight slot: the middle 16 x 16 m open (25 % of the 32 x 32 floor)
hole = 8.0
box(-O, H, -O, O, H + 1, -hole, "roof")
box(-O, H, hole, O, H + 1, O, "roof")
box(-O, H, -hole, -hole, H + 1, hole, "roof")
box(hole, H, -hole, O, H + 1, hole, "roof")

out = {
    "_why": "THE LANTERN's arena (builder B, NIGHT27 boss1; GG: 'the arenas are still way too wide ... they don't encourage using the wall ride'): a ring courtyard 32 m across and 12 m high with a floor, a roof with a skylight slot over the middle (25 % of the floor: GG, 'open is also fine') and EIGHT wall-ride segments (1 m slabs on the inner faces, kinds seg0..seg7: sector i holds the directions [i*45, (i+1)*45) deg of atan2(z, x) around the lantern; the lantern's shield flag reads the sector of the wall you ride). Behind the slabs a 2 m shell, so a segment that retracts in phase 3 leaves a recess, never the outside. ARENA-LOCAL coordinates (centre 0, 0, 0): the lantern hovers at the centre; the player enters on the south side. Generated by Tools/night/gen-lantern.py.",
    "name": "lantern-arena",
    "half": R,
    "height": H,
    "floorSize": 40,
    "killPlaneY": -30,
    "center": [0, 0, 0],
    "playerSpawn": {"x": 0, "y": 0, "z": 12, "yawDeg": 0},
    "collision": {"boxes": boxes},
}
with open("Design/maps/lantern-arena.json", "w") as f:
    json.dump(out, f, indent=1)
    f.write("\n")
print("wrote Design/maps/lantern-arena.json with", len(boxes), "boxes")
