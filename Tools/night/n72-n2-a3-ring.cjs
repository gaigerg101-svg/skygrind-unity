// NIGHT72 builder N, slice N2 (the reach audit, Tools/night/n72-reach.cjs): level 1's room a3 (1.3 RIDE) has no roof slab since 0e3f95ea5 (GG 2026-10-26: "the mini roof ...
// remove it"), and its ring walls stop at its `height` 10 m. Under the ULTRAKILL profile a player on one of a3's decks reaches deck top + 9.18 m (jump 5.07 + double jump, the
// parity lab): the 2.5 m shelves clear 10 m (11.68) and the 5 m east platform, which touches the ring, reaches 14.18: the audit's ESCAPE rows. The ring is raised to
// RING_M so the highest deck's reach (14.18) is under it with a margin; the room's own pieces (the 10 m cheeks, the runner wall) keep their heights.
// This edits the n52 plan IN PLACE (the plan the hotfix 0e3f95ea5 also edited, like n53-k-a3.cjs for a3's second pass): the level is then regenerated by levelgen and
// `node Tools/night/gen-n52-foundry.cjs --finish` (n52-foundry), `gen-n65-foundry.cjs --export a3` and `--run --slots=b1,a8` (n65-foundry). Idempotent; refuses a plan
// whose a3 is not the roofless 1.3 RIDE.
//   node Tools/night/n72-n2-a3-ring.cjs
"use strict";
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "../..");
const PLAN = "Design/levels/n52/foundry.plan.json";
const RING_M = 15; // m: 14.18 (the 5 m east platform + the double jump's 9.18) plus 0.8 m; the audit's --adjacent 2 / --double 9.18 read it as clear

const f = path.join(ROOT, PLAN);
const text = fs.readFileSync(f, "utf8");
const eol = text.includes("\r\n") ? "\r\n" : "\n";
const fmt = (o) => JSON.stringify(o, null, 1).replace(/\n/g, eol) + eol;
const plan = JSON.parse(text);
if (fmt(plan) !== text) throw new Error(PLAN + " does not round-trip in its form; not written");
const a3 = plan.rooms.find((r) => r.id === "a3");
if (!a3 || a3.name !== "1.3 RIDE" || a3.roof !== false) throw new Error("a3 is not the roofless 1.3 RIDE (name " + (a3 && a3.name) + ", roof " + (a3 && a3.roof) + "): not written");
if (a3.height === RING_M) { console.log("a3.height is already " + RING_M + ": nothing to do"); process.exit(0); }
if (a3.height !== 10) throw new Error("a3.height is " + a3.height + ", expected 10: not written");
a3.height = RING_M;
a3.height_why = "NIGHT72 N2 (Tools/night/n72-n2-a3-ring.cjs, n72-reach.cjs): a3 has no roof (0e3f95ea5), so its ring walls are the room's limit; at 10 m the 2.5 m shelves (11.68 m reach: 2.5 + the double jump's 9.18) and the 5 m east platform (14.18) clear them. 15 m: the highest deck's reach 14.18 + 0.8. The pieces inside keep their heights.";
fs.writeFileSync(f, fmt(plan));
console.log("a3.height 10 -> " + RING_M + " in " + PLAN + " (height_why added)");
