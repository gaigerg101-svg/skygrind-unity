// NIGHT57 leftover X2 (the lead; NIGHT57.md section 5, GAPS.md 1.4): docs/ROOMS.md grew into a changelog of six generations of the same
// rooms (n42, n43, n45, n46, n47, n52), so no single table said what ships. This writes an "As shipped" table at the top of ROOMS.md,
// between two markers, from the shipped levels' plans: the level a campaign run loads (the config's ON level rows: design.n52.*.levelTo,
// design.n57.kiln57.levelTo when ON), each combat / boss room's id, name, kind, par, waves, enemies, kinds and its job / verb line.
// Re-run it whenever a level row or a plan changes; the older sections below the markers stay as they are.
//   node Tools/night/n57-rooms-table.cjs [--check]      (--check: exit 1 if ROOMS.md's table is out of date)
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "../..");
const cfg = JSON.parse(fs.readFileSync(path.join(ROOT, "Design/unity-config.json"), "utf8"));
const START = "<!-- as-shipped:start (generated by Tools/night/n57-rooms-table.cjs; do not edit by hand) -->";
const END = "<!-- as-shipped:end -->";

// the shipped id per level: the newest ON level row whose levelFrom chain starts at that level's n52 id
const LEVELS = [["1", "foundry"], ["2", "iceline"], ["3", "kiln"], ["4", "span"], ["5", "spire"]];
function shippedId(name) {
  let id = "n52-" + name;
  for (const night of ["n57"]) {
    const block = cfg.design[night] || {};
    for (const row of Object.values(block))
      if (row && typeof row === "object" && row.enabled === true && row.levelFrom === id && row.levelTo) id = row.levelTo;
  }
  return id;
}
function planOf(id) {
  const m = /^n(\d+)-(.+)$/.exec(id);
  const p = path.join(ROOT, "Design/levels/n" + m[1], m[2] + ".plan.json");
  return fs.existsSync(p) ? [p, JSON.parse(fs.readFileSync(p, "utf8"))] : [p, null];
}
const short = (s, n) => (s == null ? "" : String(s).replace(/\|/g, "/").replace(/\s+/g, " ").slice(0, n));

let out = [START, "", "## As shipped (generated " + new Date().toISOString().slice(0, 10) + "; the campaign's current levels, read from the config's ON level rows and their plans)", ""];
for (const [num, name] of LEVELS) {
  const id = shippedId(name);
  const [p, plan] = planOf(id);
  if (!plan) { out.push("### Level " + num + ": " + id + " (plan not found: " + path.relative(ROOT, p).replace(/\\/g, "/") + ")", ""); continue; }
  const rooms = (Array.isArray(plan.rooms) ? plan.rooms : Object.values(plan.rooms)).filter((r) => r.kind === "room" || r.kind === "boss");
  const combat = rooms.filter((r) => r.kind === "room");
  const enemies = combat.reduce((a, r) => a + (r.waves || []).flat().length, 0);
  const kinds = [...new Set(combat.flatMap((r) => (r.waves || []).flat()))];
  out.push("### Level " + num + ": " + (plan.name || id) + " (" + id + "; " + combat.length + " combat rooms, " + enemies + " enemies, " + kinds.length + " kinds: " + kinds.join(", ") + ")", "");
  out.push("| room | name | kind | par s | waves / enemies | kinds | job / verb |", "|---|---|---|---|---|---|---|");
  for (const r of rooms) {
    const w = r.waves || [];
    out.push("| " + r.id + " | " + short(r.name, 40) + " | " + r.kind + " | " + (r.par ?? "") + " | " + w.length + " / " + w.flat().length + " | " +
      [...new Set(w.flat())].join(", ") + " | " + short(r.job57 || r.job36 || r.verb36 || "", 110) + " |");
  }
  out.push("");
}
out.push(END);
const table = out.join("\n");

const file = path.join(ROOT, "docs/ROOMS.md");
let doc = fs.readFileSync(file, "utf8");
const crlf = doc.includes("\r\n");
if (crlf) doc = doc.replace(/\r\n/g, "\n");
let next;
if (doc.includes(START.slice(0, 30))) {
  const a = doc.indexOf(START.slice(0, 30)), b = doc.indexOf(END);
  if (b < a) throw new Error("ROOMS.md: the markers are out of order");
  next = doc.slice(0, a) + table + doc.slice(b + END.length);
} else {
  const firstBreak = doc.indexOf("\n## "); // after the title and its intro, before the first level section
  if (firstBreak < 0) throw new Error("ROOMS.md: no level section found");
  next = doc.slice(0, firstBreak) + "\n" + table + "\n" + doc.slice(firstBreak);
}
if (process.argv.includes("--check")) {
  const strip = (s) => s.replace(/generated \d{4}-\d{2}-\d{2}/, "generated");
  if (strip(next) !== strip(doc)) { console.log("ROOMS.md's as-shipped table is out of date"); process.exit(1); }
  console.log("ROOMS.md's as-shipped table is current"); process.exit(0);
}
fs.writeFileSync(file, crlf ? next.replace(/\n/g, "\r\n") : next);
console.log("wrote the as-shipped table (" + table.split("\n").length + " lines) into docs/ROOMS.md");
