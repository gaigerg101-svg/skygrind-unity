# Generates Design/maps/glacier-course.json (run from the repo root): python Tools/gen-glacier.py
# THE GLACIER's course tile (NIGHT26 builder B, contract glacier): ONE 40 m tile, tile-local z from 0 to -40 (the sim places tile k at z = -40 k and keeps a sliding window of
# 8 tiles: Core/Enemies/Glacier26.cs GlacierCourse.Window), 24 m wide with 3 lanes (centres -7, 0, 7) separated by low rails (0.9 m: jump them, or use the 8 m gap in each),
# tall side walls to wall-ride, a ceiling, a boost strip per tile. The start cap is the first tile's room behind the spawn. Axis-aligned boxes only (the C# collider).
import json
tile, start, boosts = [], [], []
def box(lst, lo, hi, kind):
    lst.append({"min": list(lo), "max": list(hi), "kind": kind})
L, W, H = 40.0, 12.0, 10.0
box(tile, (-W, -0.5, -L), (W, 0, 0), "floor")
box(tile, (-W - 2, 0, -L), (-W, H, 0), "wall")
box(tile, (W, 0, -L), (W + 2, H, 0), "wall")
box(tile, (-W - 2, H, -L), (W + 2, H + 2, 0), "ceiling")
for rx in (-3.5, 3.5):
    box(tile, (rx - 0.25, 0, -14), (rx + 0.25, 0.9, 0), "rail")      # the rail's first stretch
    box(tile, (rx - 0.25, 0, -L), (rx + 0.25, 0.9, -22), "rail")     # and its second: the gap between is 8 m
boosts.append([-1.5, -30.0, 1.5, -34.0])                             # a strip in the middle lane, 4 m long
boosts.append([5.5, -8.0, 8.5, -12.0])                               # and one in the right lane
# the start cap: a closed room behind the spawn
box(start, (-W, -0.5, 0), (W, 0, 14), "floor")
box(start, (-W - 2, 0, 0), (-W, H, 14), "wall")
box(start, (W, 0, 0), (W + 2, H, 14), "wall")
box(start, (-W - 2, 0, 14), (W + 2, H, 16), "wall")
box(start, (-W - 2, H, 0), (W + 2, H + 2, 16), "ceiling")
course = {
    "_why": "THE GLACIER's course (builder B, NIGHT26 level 2; GG: 'speed skating', 'wall riding or moving', 'different surfaces'): one 40 m tile of an endless straight (tile-local z 0 to -40; tile k is at z = -40 k, the sim recycles an 8-tile window = 320 m behind and ahead of the player, no scrolling world), 24 m wide, 3 lanes (centres -7, 0, 7) split by 0.9 m rails with an 8 m gap in each, 10 m side walls to wall-ride, a ceiling, two boost strips per tile (rects x0, z0, x1, z1), the whole floor is ice (design.n26.surfaces.iceFrictionMult). `start` is the closed room behind the spawn. Generated by Tools/gen-glacier.py.",
    "name": "glacier-course", "tileLen": L, "half": W, "height": H,
    "tile": tile, "start": start, "boosts": boosts,
    "playerSpawn": {"x": 0, "y": 0, "z": 2, "yawDeg": 0},
}
json.dump(course, open('Design/maps/glacier-course.json', 'w'), indent=1)
print('wrote Design/maps/glacier-course.json')
