// NIGHT15 U3-28.2: draw a map plan (Design/maps/<id>.plan.json) as a top-down SVG with a metric grid: zones coloured
// (built ones solid, the rest hatched), walls, boxes by kind (with heights), ramps (arrow downhill), pads (arrow to the
// target), grapple nodes, doorways with their cost, loops, expert shortcuts, every spot, spawns, the landmark. The
// numbers are the plan's own (the greybox build script reads the same file), so the plan can't drift from the build.
// Usage: node Tools/map-plan-svg.cjs Design/maps/drydock.plan.json Logs/shots/n15-plan.svg
// Then render it, e.g. chrome --headless --screenshot=<png> --window-size=W,H file:///<svg>.
// Coordinates: web x east, z south: north is up on the page (svg y = z).
const fs = require('fs');
const [src, dst] = process.argv.slice(2);
if (!src || !dst) throw new Error('usage: node Tools/map-plan-svg.cjs <plan.json> <out.svg>');
const plan = JSON.parse(fs.readFileSync(src, 'utf8'));
const S = 7; // px per metre
const M = 70; // margin px
const half = plan.floorSize / 2;
const W = plan.floorSize * S + 2 * M + 360; // the legend column on the right
const H = plan.floorSize * S + 2 * M + 40;
const X = (x) => M + (x + half) * S;
const Y = (z) => M + 30 + (z + half) * S;
const f = (n) => Math.round(n * 10) / 10;
// The dusk palette (CLAUDE.md rule 8): cyan = player-usable, red-orange = enemies / danger, pale violet-white = the
// boundary; zones get muted dusk tints; the landmark is the sun's amber.
const C = {
  bg: '#14111f', grid: '#251f38', gridMajor: '#3a3156', text: '#e9e4f5', dim: '#9d93b8', wall: '#8b84a3', hull: '#6e5a4a',
  deck: '#9a8a70', slab: '#5d6f8c', rib: '#7a6552', landmark: '#ffb547', cyan: '#3fe0ff', enemy: '#ff5a36', boundary: '#e6defa',
  loop: '#7dffb0', shortcut: '#ffe46b',
};
const zoneTint = ['#3b2f5e', '#2f4a5e', '#5e3b48', '#2f5e4a', '#5e5a2f', '#4a2f5e', '#2f3f5e', '#5e452f'];
const out = [];
const el = (s) => out.push(s);
const text = (x, y, s, size = 12, color = C.text, anchor = 'middle', weight = 'normal') =>
  el(`<text x="${f(x)}" y="${f(y)}" font-family="Consolas, monospace" font-size="${size}" fill="${color}" text-anchor="${anchor}" font-weight="${weight}">${String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;')}</text>`);
const rect = (x0, z0, x1, z1, fill, stroke = 'none', sw = 0, extra = '') =>
  el(`<rect x="${f(X(Math.min(x0, x1)))}" y="${f(Y(Math.min(z0, z1)))}" width="${f(Math.abs(x1 - x0) * S)}" height="${f(Math.abs(z1 - z0) * S)}" fill="${fill}" stroke="${stroke}" stroke-width="${sw}" ${extra}/>`);
const arrow = (x0, z0, x1, z1, color, dash = '', w = 2) =>
  el(`<line x1="${f(X(x0))}" y1="${f(Y(z0))}" x2="${f(X(x1))}" y2="${f(Y(z1))}" stroke="${color}" stroke-width="${w}" ${dash ? `stroke-dasharray="${dash}"` : ''} marker-end="url(#arrow-${color.slice(1)})"/>`);
el(`<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">`);
el('<defs>');
for (const c of [C.cyan, C.loop, C.shortcut, C.text, C.dim]) {
  el(`<marker id="arrow-${c.slice(1)}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${c}"/></marker>`);
}
el(`<pattern id="hatch" width="8" height="8" patternUnits="userSpaceOnUse" patternTransform="rotate(45)"><line x1="0" y1="0" x2="0" y2="8" stroke="${C.gridMajor}" stroke-width="3"/></pattern>`);
el('</defs>');
el(`<rect width="${W}" height="${H}" fill="${C.bg}"/>`);
text(M, 34, `${plan.name}: the plan (top-down, north up, 1 square = 4 m, labels every 16 m)`, 20, C.text, 'start', 'bold');
text(M, 54, `floor ${plan.floorSize} x ${plan.floorSize} m; built tonight: ${plan.built.join(', ')}; hatched: night 2. Generated by Tools/map-plan-svg.cjs from ${src.replace(/\\/g, '/')}`, 12, C.dim, 'start');
// zones
plan.zones.forEach((z, i) => {
  const [x0, z0, x1, z1] = z.rect;
  rect(x0, z0, x1, z1, z.built ? zoneTint[i % zoneTint.length] : 'url(#hatch)', z.built ? 'none' : C.gridMajor, 1, z.built ? 'fill-opacity="0.85"' : '');
});
// grid
for (let v = -half; v <= half; v += 4) {
  const major = v % 16 === 0;
  el(`<line x1="${X(v)}" y1="${Y(-half)}" x2="${X(v)}" y2="${Y(half)}" stroke="${major ? C.gridMajor : C.grid}" stroke-width="${major ? 1.2 : 0.6}" stroke-opacity="0.7"/>`);
  el(`<line x1="${X(-half)}" y1="${Y(v)}" x2="${X(half)}" y2="${Y(v)}" stroke="${major ? C.gridMajor : C.grid}" stroke-width="${major ? 1.2 : 0.6}" stroke-opacity="0.7"/>`);
  if (major) {
    text(X(v), Y(-half) - 6, `${v}`, 10, C.dim);
    text(X(-half) - 8, Y(v) + 4, `${v}`, 10, C.dim, 'end');
  }
}
text(X(half) + 4, Y(-half) - 6, 'x', 10, C.dim, 'start');
text(X(-half) - 8, Y(half) + 14, 'z', 10, C.dim, 'end');
// floor outline
for (const b of plan.floor) rect(b.min[0], b.min[2], b.max[0], b.max[2], 'none', C.dim, 1, 'stroke-dasharray="3 3"');
// loops (under the geometry)
for (const l of plan.loops || []) {
  const pts = l.path.map(([x, z]) => `${f(X(x))},${f(Y(z))}`).join(' ');
  el(`<${l.closed ? 'polygon' : 'polyline'} points="${pts}" fill="none" stroke="${C.loop}" stroke-width="3" stroke-dasharray="10 6" stroke-opacity="0.75"/>`);
}
// walls
for (const w of plan.walls) rect(w.min[0], w.min[2], w.max[0], w.max[2], C.wall, C.boundary, 0.5);
// boxes by kind, tallest last; the height on top
const kindFill = { hull: C.hull, deck: C.deck, slab: C.slab, rib: C.rib, landmark: C.landmark };
const boxes = [...plan.boxes].sort((a, b) => a.max[1] - b.max[1]);
for (const b of boxes) {
  rect(b.min[0], b.min[2], b.max[0], b.max[2], kindFill[b.kind] || C.wall, '#000', 0.6, b.kind === 'deck' ? 'fill-opacity="0.75"' : '');
}
for (const b of boxes) {
  if (b.kind === 'rib' && b.min[1] > 0) continue;
  const w = (b.max[0] - b.min[0]) * S;
  const h = (b.max[2] - b.min[2]) * S;
  if (w < 12 && h < 12 && b.kind !== 'landmark') continue;
  const label = b.kind === 'landmark' ? `MAST ${b.max[1]} m` : `${b.max[1]}`;
  text(X((b.min[0] + b.max[0]) / 2), Y((b.min[2] + b.max[2]) / 2) + 4, label, b.kind === 'landmark' ? 12 : 10, b.kind === 'landmark' ? C.landmark : '#fff', 'middle', 'bold');
}
// ramps: the outline and an arrow downhill
for (const r of plan.ramps) {
  const [fx, fz] = r.from;
  const [tx, tz] = r.to;
  const len = Math.hypot(tx - fx, tz - fz);
  const nx = -(tz - fz) / len * r.width / 2;
  const nz = (tx - fx) / len * r.width / 2;
  const pts = [[fx + nx, fz + nz], [tx + nx, tz + nz], [tx - nx, tz - nz], [fx - nx, fz - nz]].map(([x, z]) => `${f(X(x))},${f(Y(z))}`).join(' ');
  el(`<polygon points="${pts}" fill="${C.deck}" fill-opacity="0.45" stroke="${C.text}" stroke-width="1"/>`);
  arrow(tx, tz, fx, fz, C.text, '6 4', 1.5);
  text(X((fx + tx) / 2) + 4, Y((fz + tz) / 2), `ramp ${f(len)} m, rise ${r.rise}`, 10, C.text, 'start');
}
// doorways (gates) with their zone's cost
const zoneById = Object.fromEntries(plan.zones.map((z) => [z.id, z]));
for (const d of plan.doorways) {
  const [x, z] = d.at;
  const alongX = d.face[0] === 0;
  const hw = d.width / 2;
  el(`<line x1="${f(X(alongX ? x - hw : x))}" y1="${f(Y(alongX ? z : z - hw))}" x2="${f(X(alongX ? x + hw : x))}" y2="${f(Y(alongX ? z : z + hw))}" stroke="${C.cyan}" stroke-width="5"/>`);
  const target = d.between.find((id) => id !== d.buyFrom);
  text(X(d.buyAt[0]) + (alongX ? 0 : (d.face[0] < 0 ? 18 : -18)), Y(d.buyAt[1]) + (alongX ? 14 : 4), `${zoneById[target].cost}`, 11, C.cyan, 'middle', 'bold');
}
// pads
for (const p of plan.pads) {
  const [x, y, z] = p.at;
  el(`<circle cx="${f(X(x))}" cy="${f(Y(z))}" r="${S * 1.2}" fill="none" stroke="${C.cyan}" stroke-width="2.5"/>`);
  if (p.target) arrow(x, z, p.target[0], p.target[2], C.cyan, '4 3', 1.8);
}
// grapple nodes
for (const g of plan.grapple) {
  el(`<circle cx="${f(X(g.at[0]))}" cy="${f(Y(g.at[2]))}" r="5" fill="${C.bg}" stroke="${C.cyan}" stroke-width="2.5"/>`);
  el(`<circle cx="${f(X(g.at[0]))}" cy="${f(Y(g.at[2]))}" r="1.5" fill="${C.cyan}"/>`);
}
// shortcuts
for (const s of plan.shortcuts || []) arrow(s.from[0], s.from[1], s.to[0], s.to[1], C.shortcut, '2 4', 2.5);
// spots
const sp = plan.spots;
const tag = (x, z, label, color, bg = C.bg) => {
  el(`<rect x="${f(X(x) - 9)}" y="${f(Y(z) - 8)}" width="18" height="16" rx="3" fill="${bg}" stroke="${color}" stroke-width="1.5"/>`);
  text(X(x), Y(z) + 4, label, 10, color, 'middle', 'bold');
};
for (const h of sp.hold) el(`<circle cx="${f(X(h.at[0]))}" cy="${f(Y(h.at[2]))}" r="${4 * S}" fill="none" stroke="${C.cyan}" stroke-width="1.5" stroke-dasharray="5 4"/>`);
for (const g of sp.spawns.ground) el(`<circle cx="${f(X(g[0]))}" cy="${f(Y(g[2]))}" r="3.2" fill="${C.enemy}"/>`);
for (const g of sp.spawns.high) el(`<path d="M${f(X(g[0]))},${f(Y(g[2]) - 5)} l5,9 l-10,0 z" fill="${C.enemy}"/>`);
for (const p of sp.perks) tag(p.at[0], p.at[2], 'P', C.cyan);
for (const w of sp.wallBuys) tag(w.at[0], w.at[2], 'W', C.cyan);
for (const b of sp.box) tag(b.at[0], b.at[2], '?', C.cyan);
for (const r of sp.relays) {
  el(`<path d="M${f(X(r.at[0]))},${f(Y(r.at[2]) - 9)} l9,9 l-9,9 l-9,-9 z" fill="${C.bg}" stroke="${C.landmark}" stroke-width="2"/>`);
  text(X(r.at[0]), Y(r.at[2]) + 22, r.name, 10, C.landmark, 'middle', 'bold');
}
if (sp.secretRelay) {
  el(`<path d="M${f(X(sp.secretRelay.at[0]) + 14)},${f(Y(sp.secretRelay.at[2]) - 9)} l7,7 l-7,7 l-7,-7 z" fill="none" stroke="${C.landmark}" stroke-width="1.5" stroke-dasharray="2 2"/>`);
}
if (sp.power) tag(sp.power.at[0], sp.power.at[2], 'ON', C.cyan);
if (sp.forge) tag(sp.forge.at[0], sp.forge.at[2], 'F', C.landmark);
if (sp.gadget) tag(sp.gadget.at[0], sp.gadget.at[2], 'A', C.cyan);
if (sp.exfil) {
  tag(sp.exfil.radio.at[0], sp.exfil.radio.at[2], 'R', C.text);
  for (const s of sp.exfil.sites) tag(s.at[0], s.at[2], 'X', C.text);
}
{
  const [x, , z] = sp.player.at;
  el(`<path d="M${f(X(x))},${f(Y(z) - 11)} l8,16 l-16,0 z" fill="${C.cyan}" stroke="#fff" stroke-width="1"/>`);
  arrow(x, z - 2, x, z - 9, C.cyan, '', 2);
}
// zone labels last (on top)
plan.zones.forEach((z) => {
  const [x0, z0, x1, z1] = z.rect;
  const cx = (x0 + x1) / 2;
  const top = Math.min(z0, z1) + 2.5;
  const lx = z.id === 'cradle' ? x0 + 6 : cx;
  const anchor = z.id === 'cradle' ? 'start' : 'middle';
  text(X(lx), Y(top) + 8, `${z.name}${z.cost ? ` (${z.cost})` : ' (start)'}`, 13, '#ffffff', anchor, 'bold');
  text(X(lx), Y(top) + 22, (z.verbs.favoured || []).join(' / '), 10, C.loop, anchor);
});
// legend
const lx = M + plan.floorSize * S + 40;
let ly = M + 40;
const leg = (draw, label) => {
  draw(lx + 10, ly);
  text(lx + 30, ly + 4, label, 12, C.text, 'start');
  ly += 24;
};
text(lx, ly - 14, 'LEGEND', 14, C.text, 'start', 'bold');
leg((x, y) => el(`<rect x="${x - 8}" y="${y - 7}" width="16" height="14" fill="${C.wall}"/>`), 'wall (14 m perimeter, 8 m inner)');
leg((x, y) => el(`<rect x="${x - 8}" y="${y - 7}" width="16" height="14" fill="${C.hull}"/>`), 'the hull (10 m), keel corridor between');
leg((x, y) => el(`<rect x="${x - 8}" y="${y - 7}" width="16" height="14" fill="${C.deck}"/>`), 'deck / platform (number = top, m)');
leg((x, y) => el(`<rect x="${x - 8}" y="${y - 7}" width="16" height="14" fill="${C.slab}"/>`), 'rib slab, rideable (top, m)');
leg((x, y) => el(`<rect x="${x - 8}" y="${y - 7}" width="16" height="14" fill="${C.landmark}"/>`), 'landmark: THE MAST, 64 m');
leg((x, y) => el(`<line x1="${x - 8}" y1="${y}" x2="${x + 8}" y2="${y}" stroke="${C.cyan}" stroke-width="5"/>`), 'gate (doorway) + its price');
leg((x, y) => el(`<circle cx="${x}" cy="${y}" r="7" fill="none" stroke="${C.cyan}" stroke-width="2.5"/>`), 'jump pad -> its target');
leg((x, y) => el(`<circle cx="${x}" cy="${y}" r="5" fill="${C.bg}" stroke="${C.cyan}" stroke-width="2.5"/>`), 'ARCLINE grapple node');
leg((x, y) => el(`<line x1="${x - 8}" y1="${y}" x2="${x + 8}" y2="${y}" stroke="${C.loop}" stroke-width="3" stroke-dasharray="6 4"/>`), 'training loop');
leg((x, y) => el(`<line x1="${x - 8}" y1="${y}" x2="${x + 8}" y2="${y}" stroke="${C.shortcut}" stroke-width="2.5" stroke-dasharray="2 4"/>`), 'expert shortcut (visible)');
leg((x, y) => el(`<circle cx="${x}" cy="${y}" r="9" fill="none" stroke="${C.cyan}" stroke-width="1.5" stroke-dasharray="4 3"/>`), 'HOLD ring spot (r 4 m)');
leg((x, y) => el(`<path d="M${x},${y - 9} l9,9 l-9,9 l-9,-9 z" fill="${C.bg}" stroke="${C.landmark}" stroke-width="2"/>`), 'PROTOCOL relay');
leg((x, y) => el(`<circle cx="${x}" cy="${y}" r="3.2" fill="${C.enemy}"/>`), 'enemy spawn, ground');
leg((x, y) => el(`<path d="M${x},${y - 5} l5,9 l-10,0 z" fill="${C.enemy}"/>`), 'enemy spawn, high');
leg((x, y) => el(`<path d="M${x},${y - 9} l8,16 l-16,0 z" fill="${C.cyan}"/>`), 'player spawn (facing north)');
for (const [k, v] of [['P', 'perk'], ['W', 'wall buy'], ['?', 'mystery box spot'], ['ON', 'power switch'], ['F', 'THE FORGE'], ['A', 'ARCLINE (buy)'], ['R', 'exfil radio'], ['X', 'exfil site']]) {
  leg((x, y) => { tag((x - X(0)) / S, (y - Y(0)) / S, k, k === 'F' ? C.landmark : C.cyan); }, v);
}
ly += 10;
text(lx, ly, 'Verbs per zone (green, under each name).', 11, C.dim, 'start');
ly += 16;
text(lx, ly, 'Heights are box tops in metres.', 11, C.dim, 'start');
// scale bar
el(`<line x1="${X(-half)}" y1="${Y(half) + 22}" x2="${X(-half + 16)}" y2="${Y(half) + 22}" stroke="${C.text}" stroke-width="3"/>`);
text(X(-half + 8), Y(half) + 36, '16 m', 11, C.text);
el('</svg>');
fs.writeFileSync(dst, out.join('\n'));
console.log(`wrote ${dst} (${W} x ${H} px)`);
