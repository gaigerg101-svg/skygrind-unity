# Generates Design/maps/monolith-arena.json (run from the repo root): python Tools/gen-monolith.py
import json
# the arena: a flat closed room, 52 m square (the web's abyssHalf 24 plus a margin), walls 16 m
boxes = []
def box(lo, hi, kind):
    boxes.append({"min": list(lo), "max": list(hi), "kind": kind})
H = 26.0
W = 16.0
box((-H - 2, -0.5, -H - 2), (H + 2, 0, H + 2), "floor")
box((-H - 2, 0, -H - 2), (H + 2, W, -H), "wall")
box((-H - 2, 0, H), (H + 2, W, H + 2), "wall")
box((-H - 2, 0, -H), (-H, W, H), "wall")
box((H, 0, -H), (H + 2, W, H), "wall")
box((-H - 2, W, -H - 2), (H + 2, W + 2, H + 2), "ceiling")
arena = {
    "_why": "MONOLITH's arena (builder B, NIGHT24 leftover 8): a closed flat room built only from axis-aligned boxes, 52 m square and 16 m high: the Grinder's flat floor without its columns (bossKit.arenas.monolith: flat), the web's arenaHalf 18 for the boss and its rings (ringMaxRadius 34) running to the walls. ARENA-LOCAL coordinates (centre 0, 0, 0). The boss rises at the centre; the player enters on the south side. Generated by Tools/gen-monolith.py.",
    "name": "monolith-arena", "half": H, "height": W, "floorSize": 56, "killPlaneY": -30, "center": [0, 0, 0],
    "playerSpawn": {"x": 0, "y": 0, "z": 22, "yawDeg": 0},
    "collision": {"boxes": boxes},
}
json.dump(arena, open('Design/maps/monolith-arena.json', 'w'), indent=1)
print('wrote Design/maps/monolith-arena.json')
