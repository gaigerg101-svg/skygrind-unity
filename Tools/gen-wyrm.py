# ---------------- the arena ----------------
H = 30.0
boxes = []
def box(lo, hi, kind):
    boxes.append({"min": [lo[0], lo[1], lo[2]], "max": [hi[0], hi[1], hi[2]], "kind": kind})
box((-32, -0.5, -32), (32, 0, 32), "floor")
box((-32, 0, -32), (32, H, -30), "wall")
box((-32, 0, 30), (32, H, 32), "wall")
box((-32, 0, -30), (-30, H, 30), "wall")
box((30, 0, -30), (32, H, 30), "wall")
box((-32, H, -32), (32, H + 2, 32), "ceiling")
# corner stairs: the square room becomes a rounder one (cylinder-ish, 60 m across)
for sx in (-1, 1):
    for sz in (-1, 1):
        for (a, b) in ((18, 26), (22, 22), (26, 18)):
            x0, x1 = sorted((sx * a, sx * 30))
            z0, z1 = sorted((sz * b, sz * 30))
            box((x0, 0, z0), (x1, H, z1), "wall")
pillars = []
for sx in (-1, 1):
    for sz in (-1, 1):
        cx, cz = sx * 10.0, sz * 10.0
        box((cx - 2, 0, cz - 2), (cx + 2, H, cz + 2), "pillar")
        pillars.append([cx, cz])
platforms = []
for ang, y in ((30, 5.5), (150, 8.5), (270, 11.5)):
    a = math.radians(ang)
    cx, cz = 24.5 * math.cos(a), 24.5 * math.sin(a)
    box((cx - 3, y - 0.5, cz - 3), (cx + 3, y + 0.5, cz + 3), "platform")
    platforms.append([r1(cx), y, r1(cz)])
arena = {
    "_why": "THE KILN WYRM's arena (DESIGN24-bosses.md section 1, builder B NIGHT24): a closed room built only from axis-aligned boxes for the C# collider: 60 m across, 30 m high, the corners stepped to read as a cylinder, 4 full-height pillars, 3 floating platforms (5.5, 8.5 and 11.5 m up; reach them by the coil's rise, a wall kick or a boosted jump), 4 tall walls to kick from. Coordinates are ARENA-LOCAL (centre 0, 0, 0, floor y 0): the layer-1 builder offsets them to the boss room. The player enters at playerSpawn (the south wall, a nook the worm stays 6 m clear of); the worm emerges from the floor hole at the centre-north. Not a SurvivalMap export: no nav grid, no zones (nothing walks here but the player). Generated by a script from the same numbers as Design/bosses/wyrm.json.",
    "name": "wyrm-arena",
    "half": 30, "height": H, "floorSize": 64, "killPlaneY": -30,
    "center": [0, 0, 0],
    "playerSpawn": {"x": 0, "y": 0, "z": 27.5, "yawDeg": 0},
    "collision": {"boxes": boxes},
    "pillars": pillars,
    "platforms": platforms,
}
json.dump(arena, open(OUT_ARENA, "w"), indent=1)
print("wrote", OUT_PATHS, OUT_ARENA, len(boxes), "boxes", file=sys.stderr)
