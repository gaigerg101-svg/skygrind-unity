# Generates Design/maps/hulk-arena.json (run from the repo root): python Tools/gen-hulk.py
# THE SLAG HULK's room (NIGHT26 builder B, contract hulk): a closed 26 m square room, two pillars, floor + walls + ceiling, built only from
# axis-aligned boxes (the C# collider's kind). GG: the first map is far too wide, so level 1's boss room is small.
import json
boxes = []
def box(lo, hi, kind):
    boxes.append({"min": list(lo), "max": list(hi), "kind": kind})
H = 13.0   # half width: 26 m across inside
W = 12.0   # wall height
box((-H - 2, -0.5, -H - 2), (H + 2, 0, H + 2), "floor")
box((-H - 2, 0, -H - 2), (H + 2, W, -H), "wall")
box((-H - 2, 0, H), (H + 2, W, H + 2), "wall")
box((-H - 2, 0, -H), (-H, W, H), "wall")
box((H, 0, -H), (H + 2, W, H), "wall")
box((-H - 2, W, -H - 2), (H + 2, W + 2, H + 2), "ceiling")
# two pillars, off the middle and off each other's diagonal: cover from a charge and something to circle (3 x 3 m, 8 m high)
for cx, cz in ((-5.5, -2.5), (5.5, 2.5)):
    box((cx - 1.5, 0, cz - 1.5), (cx + 1.5, 8.0, cz + 1.5), "pillar")
arena = {
    "_why": "THE SLAG HULK's arena (builder B, NIGHT26 contract hulk; GG: the first map's arena is far too wide): a closed room 26 m across and 12 m high built only from axis-aligned boxes: a floor, four walls, a ceiling and two 3 x 3 m pillars (cover from the charge, something to circle; the charge stops at a wall or a pillar and the hulk is stunned there). ARENA-LOCAL coordinates (centre 0, 0, 0). The hulk walks in at the centre; the player enters on the south side. Generated by Tools/gen-hulk.py.",
    "name": "hulk-arena", "half": H, "height": W, "floorSize": 30, "killPlaneY": -30, "center": [0, 0, 0],
    "playerSpawn": {"x": 0, "y": 0, "z": 10, "yawDeg": 0},
    "collision": {"boxes": boxes},
}
json.dump(arena, open('Design/maps/hulk-arena.json', 'w'), indent=1)
print('wrote Design/maps/hulk-arena.json')
