        /// <summary>Every place the player must reach: the map's spots, and the design block's when the map has none of its own.</summary>
        static List<ValidateSpot> Spots(GameConfig cfg, Dictionary<string, object> map, Dictionary<string, object> data)
        {
            var list = new List<ValidateSpot>();
            if (L(Get(data, "perkSpots")) is List<object> perks)
                foreach (object o in perks) AddXyz(list, $"perk {Get(O(o), "perk")}", o);
            if (Get(data, "forgeSpot") != null) AddXyz(list, "forge", Get(data, "forgeSpot"));
            foreach (string row in new[] { "armoryWall", "armoryRack", "armoryBack" })
                if (O(Get(data, row)) is Dictionary<string, object> w)
                {
                    bool zPlane = w.ContainsKey("xs");
                    var slots = L(w[zPlane ? "xs" : "zs"]);
                    for (int i = 0; i < slots.Count; i++)
                    {
                        double plane = N(w[zPlane ? "z" : "x"]), s = N(slots[i]);
                        list.Add(new ValidateSpot { label = $"{row} gun {i}", x = zPlane ? s : plane, y = N(w["y"]), z = zPlane ? plane : s });
                    }
                }
            if (L(Get(data, "trapSpots")) is List<object> traps)
                foreach (object o in traps)
                {
                    var d = O(o);
                    AddXyz(list, $"trap {Get(d, "trap")}", o);
                    list.Add(new ValidateSpot { label = $"trap {Get(d, "trap")} switch", x = N(d["sx"]), y = N(d["y"]), z = N(d["sz"]) });
                }
            if (L(Get(data, "gadgetSpots")) is List<object> gadgets)
                foreach (object o in gadgets) AddXyz(list, $"gadget {Get(O(o), "gadget")}", o);
            if (L(Get(data, "holdSpots")) is List<object> holds)
                for (int i = 0; i < holds.Count; i++) AddXyz(list, $"hold ring {i}", holds[i]);
            if (L(Get(data, "relaySpots")) is List<object> relays)
                foreach (object o in relays) AddXyz(list, $"relay {Get(O(o), "id")}", o);
            if (Get(data, "secretRelay") != null) AddXyz(list, $"secret relay {Get(O(Get(data, "secretRelay")), "id")}", Get(data, "secretRelay"));
            if (L(Get(data, "zones")) is List<object> zones)
                foreach (object z in zones)
                    if (L(Get(O(z), "spots")) is List<object> buys)
                        for (int i = 0; i < buys.Count; i++) AddXyz(list, $"gate {Get(O(z), "id")} {i}", buys[i]);
            var mapSpots = O(Get(map, "spots"));
            object box = Get(mapSpots, "box") ?? (cfg.Has("design.box.spots") ? cfg.Get("design.box.spots") : null);
            string boxFrom = Get(mapSpots, "box") != null ? "spots.box" : "design.box";
            if (L(box) is List<object> boxes)
                for (int i = 0; i < boxes.Count; i++) AddXyz(list, $"mystery box {i} ({boxFrom})", boxes[i]);
            object power = Get(mapSpots, "power") ?? (cfg.Has("design.power.spot") ? cfg.Get("design.power.spot") : null);
            if (power != null) AddXyz(list, $"power switch ({(Get(mapSpots, "power") != null ? "spots.power" : "design.power")})", power);
            var exfil = O(Get(mapSpots, "exfil"));
            object radio = exfil != null ? Get(exfil, "radio") : cfg.Has("design.exfil.radio") ? cfg.Get("design.exfil.radio") : null;
            object sites = exfil != null ? Get(exfil, "sites") : cfg.Has("design.exfil.sites") ? cfg.Get("design.exfil.sites") : null;
            string exfilFrom = exfil != null ? "spots.exfil" : "design.exfil";
            if (radio != null) AddXyz(list, $"exfil radio ({exfilFrom})", radio);
            if (L(sites) is List<object> siteList)
                for (int i = 0; i < siteList.Count; i++) AddXyz(list, $"exfil site {i} ({exfilFrom})", siteList[i]);
            return list;
        }

        /// <summary>The grid node a player at the spot stands on: the closest within `reach` across and `reachHeight` up or down.</summary>
        static int GridSpotNode(NavGrid g, double x, double y, double z, int r, double reach, double reachHeight)
        {
            int ci = (int)Math.Floor((x - g.origin) / g.cell), ck = (int)Math.Floor((z - g.origin) / g.cell);
            int best = -1;
            double bestD = double.PositiveInfinity;
            for (int k = ck - r; k <= ck + r; k++)
            {
                if (k < 0 || k >= g.size) continue;
                for (int i = ci - r; i <= ci + r; i++)
                {
                    if (i < 0 || i >= g.size) continue;
                    int c = k * g.size + i;
                    double dx = g.ColX(c) - x, dz = g.ColZ(c) - z;
                    double across = Math.Sqrt(dx * dx + dz * dz);
                    if (across > reach) continue;
                    for (int n = g.colStart[c]; n < g.colStart[c + 1]; n++)
                    {
                        double dy = g.y[n] - y;
                        if (Math.Abs(dy) > reachHeight) continue;
                        double d = across * across + dy * dy;
                        if (d < bestD)
                        {
                            bestD = d;
                            best = n;
                        }
                    }
                }
            }
            return best;
        }

        /// <summary>The graph node nearest a spot within `across` m horizontally and `height` m vertically (height weighs double).</summary>
        static int GraphSpotNode(NavGraph graph, ValidateSpot s, double across, double height, out double away)
        {
            int best = -1;
            double bestD = double.PositiveInfinity;
            away = 0;
            for (int i = 0; i < graph.nodes.Count; i++)
            {
                NavNode n = graph.nodes[i];
                double dx = n.x - s.x, dz = n.z - s.z, dy = n.y - s.y;
                double h = Math.Sqrt(dx * dx + dz * dz);
                if (h > across || Math.Abs(dy) > height) continue;
                double d = h * h + 4 * dy * dy;
                if (d < bestD)
                {
                    bestD = d;
                    best = i;
                    away = Math.Sqrt(h * h + dy * dy);
                }
            }
            return best;
        }

        /// <summary>An aimed pad's landing: the grid node within one cell (3 x 3 columns) closest in height, if within MapPadLandTolerance.</summary>
        static int LandingNode(NavGrid g, double x, double y, double z, out double bestDy)
        {
            int ci = (int)Math.Floor((x - g.origin) / g.cell), ck = (int)Math.Floor((z - g.origin) / g.cell);
            int best = -1;
            bestDy = double.PositiveInfinity;
            for (int k = ck - 1; k <= ck + 1; k++)
            {
                if (k < 0 || k >= g.size) continue;
                for (int i = ci - 1; i <= ci + 1; i++)
                {
                    if (i < 0 || i >= g.size) continue;
                    int c = k * g.size + i;
                    for (int n = g.colStart[c]; n < g.colStart[c + 1]; n++)
                    {
                        double dy = Math.Abs(g.y[n] - y);
                        if (dy < bestDy)
                        {
                            bestDy = dy;
                            best = n;
                        }
                    }
                }
            }
            return bestDy <= UnityTuning.MapPadLandTolerance ? best : -1;
        }

        /// <summary>For an unreachable spot: how high it sits over the grid near it, and the pad landing and grapple node nearest it.</summary>
        static string Nearby(NavGrid g, Dictionary<string, object> map, Dictionary<string, object> data, ValidateSpot s)
        {
            int ci = (int)Math.Floor((s.x - g.origin) / g.cell), ck = (int)Math.Floor((s.z - g.origin) / g.cell);
            double below = double.NegativeInfinity;
            for (int k = ck - 2; k <= ck + 2; k++)
                for (int i = ci - 2; i <= ci + 2; i++)
                {
                    if (k < 0 || k >= g.size || i < 0 || i >= g.size) continue;
                    int c = k * g.size + i;
                    for (int n = g.colStart[c]; n < g.colStart[c + 1]; n++) if (g.y[n] <= s.y + 0.5 && g.y[n] > below) below = g.y[n];
                }
            var parts = new List<string>
            {
                double.IsNegativeInfinity(below) ? "no grid node under it within 2 m across" : $"the highest grid node under it (2 m across) is {F(s.y - below)} m lower",
            };
            double padBest = double.PositiveInfinity, nodeBest = double.PositiveInfinity;
            if (L(Get(data, "pads") ?? Get(map, "pads")) is List<object> pads)
                foreach (object o in pads)
                    if (Get(O(o), "target") is Dictionary<string, object> t)
                        padBest = Math.Min(padBest, Dist(s, N(t["x"]), N(t["y"]), N(t["z"])));
            if (L(Get(data, "grappleNodes") ?? Get(map, "grappleNodes")) is List<object> nodes)
                foreach (object o in nodes)
                {
                    var d = O(o);
                    nodeBest = Math.Min(nodeBest, Dist(s, N(d["x"]), N(d["y"]), N(d["z"])));
                }
            if (!double.IsInfinity(padBest)) parts.Add($"the nearest pad landing is {F(padBest)} m away");
            if (!double.IsInfinity(nodeBest)) parts.Add($"the nearest grapple node {F(nodeBest)} m");
            return string.Join("; ", parts);
        }

        static double Dist(ValidateSpot s, double x, double y, double z) => Math.Sqrt((s.x - x) * (s.x - x) + (s.y - y) * (s.y - y) + (s.z - z) * (s.z - z));

        // --- graph searches ---------------------------------------------------------------------------------------------

        /// <summary>Breadth-first reach on the grid's links from `from` (forward, or backward: who can reach `from`), through allowed nodes.</summary>
        static bool[] GridReach(NavGrid g, int from, bool backward, Func<int, bool> allowed)
        {
            var seen = new bool[g.count];
            var queue = new Queue<int>();
            seen[from] = true;
            queue.Enqueue(from);
            while (queue.Count > 0)
            {
                int v = queue.Dequeue();
                int a = backward ? g.revStart[v] : g.linkStart[v], b = backward ? g.revStart[v + 1] : g.linkStart[v + 1];
                for (int i = a; i < b; i++)
                {
                    int u = backward ? g.revFrom[i] : g.linkTo[i];
                    if (seen[u] || !allowed(u)) continue;
                    seen[u] = true;
                    queue.Enqueue(u);
                }
            }
            return seen;
        }

        /// <summary>The same on the player's graph's edges.</summary>
        static bool[] GraphReach(NavGraph graph, int from, bool backward, Func<int, bool> allowed)
        {
            int n = graph.nodes.Count;
            List<int>[] reverse = null;
            if (backward)
            {
                reverse = new List<int>[n];
                for (int i = 0; i < n; i++) reverse[i] = new List<int>();
                for (int i = 0; i < n; i++) foreach (NavEdge e in graph.edges[i]) reverse[e.to].Add(i);
            }
            var seen = new bool[n];
            var queue = new Queue<int>();
            seen[from] = true;
            queue.Enqueue(from);
            while (queue.Count > 0)
            {
                int v = queue.Dequeue();
                if (backward)
                {
                    foreach (int u in reverse[v])
                    {
                        if (seen[u] || !allowed(u)) continue;
                        seen[u] = true;
                        queue.Enqueue(u);
                    }
                }
                else
                {
                    foreach (NavEdge e in graph.edges[v])
                    {
                        if (seen[e.to] || !allowed(e.to)) continue;
                        seen[e.to] = true;
                        queue.Enqueue(e.to);
                    }
                }
            }
            return seen;
        }

        /// <summary>
        /// The grid nodes with no grid way back to the spawn, grouped into components (linked either way among themselves).
        /// The player leaves a component when one of its graph nodes reaches the spawn on the player's graph, or when a
        /// neighbouring column (8 around a node) holds a node lower by more than config ai.grid.step outside it (a drop: no
        /// fall damage in SURVIVAL, config's only fallDamage is the boss arena's). A component the player can't leave either
        /// is a trap: a FINDING when it has MapIslandMinNodes or more nodes or holds a spot or a spawn node. The others are
        /// the enemies' islands (a husk there stays there): one PASS row counts them and the spawn nodes on them.
        /// </summary>
        static void Islands(NavGrid g, bool[] back, Dictionary<int, List<string>> holder, Dictionary<int, int> spawnAt, Dictionary<int, List<int>> gridToGraph, bool[] graphBack, double step, List<ValidateRow> rows)
        {
            var comp = new int[g.count];
            for (int n = 0; n < g.count; n++) comp[n] = -1;
            int next = 0, tinyCount = 0, tinyNodes = 0, enemyCount = 0, enemyNodes = 0, enemySpawns = 0, enemyByDrop = 0;
            var enemyHolds = new List<string>();
            var queue = new Queue<int>();
            var members = new List<int>();
            var traps = new List<(int size, string where, string holds, bool graphless)>();
            for (int s = 0; s < g.count; s++)
            {
                if (back[s] || comp[s] >= 0) continue;
                int id = next++;
                comp[s] = id;
                queue.Enqueue(s);
                members.Clear();
                int size = 0, spawnCount = 0;
                bool playerOut = false, anyGraph = false;
                double x0 = double.PositiveInfinity, x1 = double.NegativeInfinity, z0 = double.PositiveInfinity, z1 = double.NegativeInfinity, y0 = double.PositiveInfinity, y1 = double.NegativeInfinity;
                var holds = new List<string>();
                while (queue.Count > 0)
                {
                    int v = queue.Dequeue();
                    size++;
                    members.Add(v);
                    double x = g.NodeX(v), z = g.NodeZ(v);
                    x0 = Math.Min(x0, x);
                    x1 = Math.Max(x1, x);
                    z0 = Math.Min(z0, z);
                    z1 = Math.Max(z1, z);
                    y0 = Math.Min(y0, g.y[v]);
                    y1 = Math.Max(y1, g.y[v]);
                    if (holder.TryGetValue(v, out List<string> h)) holds.AddRange(h);
                    if (spawnAt.TryGetValue(v, out int sc)) spawnCount += sc;
                    if (graphBack != null && gridToGraph.TryGetValue(v, out List<int> js))
                        foreach (int j in js)
                        {
                            anyGraph = true;
                            if (graphBack[j]) playerOut = true;
                        }
                    for (int li = g.linkStart[v]; li < g.linkStart[v + 1]; li++)
                    {
                        int u = g.linkTo[li];
                        if (back[u] || comp[u] >= 0) continue;
                        comp[u] = id;
                        queue.Enqueue(u);
                    }
                    for (int ri = g.revStart[v]; ri < g.revStart[v + 1]; ri++)
                    {
                        int u = g.revFrom[ri];
                        if (back[u] || comp[u] >= 0) continue;
                        comp[u] = id;
                        queue.Enqueue(u);
                    }
                }
                string where = $"x {F(x0)} .. {F(x1)}, z {F(z0)} .. {F(z1)}, y {F(y0)} .. {F(y1)}";
                bool byDrop = false;
                if (!playerOut)
                    foreach (int v in members)
                    {
                        if (CanDrop(g, v, comp, id, step))
                        {
                            byDrop = true;
                            break;
                        }
                    }
                if (playerOut || byDrop)
                {
                    enemyCount++;
                    enemyNodes += size;
                    enemySpawns += spawnCount;
                    if (!playerOut) enemyByDrop++;
                    continue;
                }
                if (size < UnityTuning.MapIslandMinNodes && holds.Count == 0 && spawnCount == 0)
                {
                    tinyCount++;
                    tinyNodes += size;
                    continue;
                }
                if (spawnCount > 0) holds.Add($"{spawnCount} spawn nodes");
                traps.Add((size, where, string.Join(", ", holds), graphBack != null && !anyGraph));
            }
            traps.Sort((a, b) => b.size.CompareTo(a.size));
            foreach (var c in traps)
                rows.Add(new ValidateRow
                {
                    check = "island", pass = false,
                    detail = $"{c.size} grid nodes the player can't leave (no way back on the enemies' grid or the player's graph, no drop to lower ground)"
                        + (c.graphless ? " and no graph node stands there" : "") + $": {c.where}" + (c.holds.Length > 0 ? $"; holds {c.holds}" : ""),
                });
            rows.Add(new ValidateRow
            {
                check = "enemy-only islands", pass = true,
                detail = $"{enemyCount} components ({enemyNodes} grid nodes) the enemies' grid can't leave and the player can ({enemyCount - enemyByDrop} by the player's graph, {enemyByDrop} only by a drop); {enemySpawns} spawn nodes stand on them (a husk spawned there waits for the player)",
            });
            rows.Add(new ValidateRow
            {
                check = "small islands", pass = true,
                detail = $"{tinyCount} components under {UnityTuning.MapIslandMinNodes} grid nodes ({tinyNodes} nodes) the player can't leave, holding no spot or spawn node",
            });
        }

        /// <summary>True when a column next to node v (8 around) holds a node lower than v by more than `step`, outside v's component.</summary>
        static bool CanDrop(NavGrid g, int v, int[] comp, int id, double step)
        {
            int c = g.col[v], ci = c % g.size, ck = c / g.size;
            for (int k = ck - 1; k <= ck + 1; k++)
                for (int i = ci - 1; i <= ci + 1; i++)
                {
                    if ((k == ck && i == ci) || k < 0 || k >= g.size || i < 0 || i >= g.size) continue;
                    int cc = k * g.size + i;
                    for (int n = g.colStart[cc]; n < g.colStart[cc + 1]; n++)
                        if (g.y[n] < g.y[v] - step && comp[n] != id) return true;
                }
            return false;
        }
