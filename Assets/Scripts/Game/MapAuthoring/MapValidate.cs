// NIGHT15 U3-28.4 (builder P): SKYGRIND/Map/Validate's checks on an exported map JSON (never the scene). Two graphs:
// - the player's: RIVAL's nav graph (Core/Nav/NavGraph.cs, built as BotNav.Build builds it: the map's own Octree, the
//   core at 'flat', its nav grid), whose edges are moves the Mover can fly (walk at config ground.walkSpeed, drops, running
//   / standing / dash jumps, double jumps, aimed pads), costed in seconds; zones and spots are checked on it, with
//   Core/Nav/Astar.cs for each spot's time from the player spawn;
// - the enemies': the nav grid (NavGrid.FromExport: 1 m columns, walk, 2.2 m jumps, 5 m drops, gaps; config.ai.grid);
//   spawns, pad landings and walkable islands are checked on it, each spot also gets its grid A* (Flow.GridPath) time.
// The graph crosses locked zones (as BotNav's: no force fields), so a zone's reach is judged by the nodes a path visits.
// A spot may carry a designed verb gate (a Unity-authored map's "verb", UnityTuning.MapVerbs: the lead, NIGHT15): when the
// graph can't reach it and its zone is reached, its row is VERB, not a FINDING (VerbRule); the web's maps have none.
// Output: Reports/MAP-<id>-validate.md, one table row per check (PASS / FINDING with the numbers) and the findings count.
// Pure (no UnityEngine).
using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Text;
using Skygrind.Core;

namespace Skygrind.Game.MapAuthoring
{
    public static class MapValidate
    {
        struct ValidateRow
        {
            public string check;
            public bool pass;
            public bool verb; // pass and verb: "VERB" (a designed verb gate: not a finding)
            public string detail;
        }

        /// <summary>A place the validator checks: a spot, a spawn or a pad.</summary>
        struct ValidateSpot
        {
            public string label;
            public double x, y, z;
            public string verb; // the spot's "verb" ("" none)
        }

        static string F(double v)
        {
            double r = Math.Round(v, 2);
            return (r == 0 ? 0 : r).ToString("0.##", CultureInfo.InvariantCulture); // never "-0"
        }
        static string P(double x, double y, double z) => $"({F(x)}, {F(y)}, {F(z)})";
        static Dictionary<string, object> O(object o) => o as Dictionary<string, object>;
        static List<object> L(object o) => o as List<object>;
        static object Get(Dictionary<string, object> d, string key) => d != null && d.TryGetValue(key, out object v) ? v : null;
        static double N(object o) => PortData.Num(o);

        /// <summary>The report for one map (markdown) and its FINDING count. `label` names the file in the header.</summary>
        public static (string markdown, int findings) Run(GameConfig cfg, Dictionary<string, object> map, string label = null)
        {
            var rows = new List<ValidateRow>();
            string id = Get(map, "name") as string ?? "map";
            var data = O(Get(map, "data")) ?? new Dictionary<string, object>();
            var gridJson = O(Get(map, "navGrid"));
            var head = new StringBuilder();
            head.Append($"# MAP {id}: validation\n\n");
            head.Append("Generated by `SKYGRIND/Map/Validate` (Assets/Scripts/Game/MapAuthoring/MapValidate.cs, NIGHT15 U3-28.4) from the exported map JSON");
            head.Append(label != null ? $" `{label}`" : "").Append(", not from the scene.\n\n");
            if (gridJson == null)
            {
                rows.Add(new ValidateRow { check = "nav grid", pass = false, detail = "the map has no navGrid: export it with SKYGRIND/Map/Export first" });
                return Finish(head, rows);
            }
            NavGrid g = NavGrid.FromExport(gridJson);
            double walkSpeed = cfg.Num("ground.walkSpeed"), heuristicSpeed = cfg.movement.dash.speed;
            double lookBelow = cfg.Num("ai.grid.lookBelow"), lookAbove = cfg.Num("ai.grid.lookAbove");
            double reach = cfg.Num("buy.reach"), reachHeight = cfg.Num("buy.reachHeight"), graphAcross = cfg.Num("nav.floorSpacing");
            double floorSize = N(Get(map, "floorSize")), killPlaneY = N(Get(map, "killPlaneY"));

            // --- the player's graph (BotNav.Build's composition) ---
            NavGraph graph = null;
            SurvivalMap sm = null;
            try
            {
                sm = SurvivalMap.FromExport(map);
                CoreGrid core = sm.CreateCore(cfg.movement);
                var world = new GameWorld(sm.BuildOctree(), core);
                graph = NavGraph.Build(NavMap.From(sm), world, cfg, core, NavGrid.FromExport(gridJson));
            }
            catch (Exception e)
            {
                rows.Add(new ValidateRow { check = "nav graph", pass = false, detail = $"RIVAL's nav graph could not be built on this map ({e.GetType().Name}: {e.Message}): zones and spots are checked on the grid only" });
            }
            int edgeCount = 0;
            if (graph != null) foreach (List<NavEdge> e in graph.edges) edgeCount += e.Count;
            head.Append($"- The player's graph: RIVAL's nav graph, {(graph != null ? $"{graph.nodes.Count} nodes, {edgeCount} edges" : "not built")} (the report holds no timings: a rerun on the same file writes the same text). ");
            head.Append($"A spot's time is its Astar.Path cost from the player spawn in seconds (walk edges at config `ground.walkSpeed` = {F(walkSpeed)} m/s; ");
            head.Append("flights and pads at their flown time); its node is the graph node within config `nav.floorSpacing` = ");
            head.Append($"{F(graphAcross)} m across and `buy.reachHeight` = {F(reachHeight)} m up or down. The graph flies ");
            head.Append($"{string.Join(", ", NavGraph.FLIGHT_KINDS)}, drops and pads (NavGraph.FLIGHT_KINDS), and stands on the box kinds in config ");
            head.Append("`nav.walkWalkers`: no wall ride, slide jump or grapple, so a perch only those reach is a FINDING here and may still be the player's.\n");
            head.Append($"- The enemies' grid: the nav grid, {g.count} nodes, {g.linkTo.Length} links, {g.size} x {g.size} columns of {F(g.cell)} m from {F(g.origin)}; ");
            head.Append($"a spot's grid node is within config `buy.reach` = {F(reach)} m across; its grid time is Flow.GridPath's m-equivalent cost over the run speed.\n");

            // --- the player spawn ---
            var spawnJson = O(Get(data, "playerSpawn")) ?? O(Get(O(Get(map, "spawns")), "playerSpawn"));
            int start = -1, startG = -1;
            if (spawnJson != null && spawnJson.ContainsKey("x"))
            {
                double sx = N(spawnJson["x"]), sy = N(spawnJson["y"]), sz = N(spawnJson["z"]);
                start = g.NodeAt(sx, sy, sz, lookBelow, lookAbove);
                if (graph != null) startG = Astar.NearestNode(graph, new Vec3(sx, sy, sz));
                rows.Add(new ValidateRow
                {
                    check = "player spawn", pass = start >= 0 && (graph == null || startG >= 0),
                    detail = (start >= 0 ? $"{P(sx, sy, sz)} stands on grid node {start} (y {F(g.y[start])}, zone tag {g.tag[start]})" : $"{P(sx, sy, sz)}: no grid node under it")
                        + (startG >= 0 ? $"; graph node {startG} at {P(graph.nodes[startG].x, graph.nodes[startG].y, graph.nodes[startG].z)}" : ""),
                });
            }
            else rows.Add(new ValidateRow { check = "player spawn", pass = false, detail = "no {x, y, z} player spawn" });

            // --- zones, in price order, on the player's graph ---
            var zoneList = L(Get(data, "zones")) ?? new List<object>();
            string startZone = Get(data, "startZone") as string ?? "";
            var zoneIds = new List<string>();
            var zoneCost = new List<double>();
            foreach (object z in zoneList)
            {
                var d = O(z);
                string zid = Get(d, "id") as string ?? "";
                zoneIds.Add(zid);
                zoneCost.Add(d.TryGetValue("cost", out object c) ? N(c) : cfg.Has($"zones.costs.{zid}") ? cfg.Num($"zones.costs.{zid}") : 0);
            }
            int[] graphTag = null;
            if (graph != null)
            {
                graphTag = new int[graph.nodes.Count];
                for (int i = 0; i < graphTag.Length; i++)
                {
                    NavNode n = graph.nodes[i];
                    graphTag[i] = sm != null && sm.zoneParts.Count > 0 ? ZoneMath.ZoneIndexAt(sm.zoneParts, n.x, n.y + 1, n.z) : -1; // survival/zones.js tagAt
                }
            }
            var zoneNodes = new int[zoneIds.Count];
            for (int n = 0; n < g.count; n++) if (g.tag[n] >= 0 && g.tag[n] < zoneNodes.Length) zoneNodes[g.tag[n]]++;
            var zoneGraphNodes = new int[zoneIds.Count];
            if (graphTag != null) foreach (int tag in graphTag) if (tag >= 0 && tag < zoneGraphNodes.Length) zoneGraphNodes[tag]++;
            int startIndex = zoneIds.IndexOf(startZone);
            var zoneReached = new bool[zoneIds.Count];
            if (zoneIds.Count > 0)
            {
                bool inStart = start >= 0 && g.tag[start] == startIndex;
                if (startIndex >= 0) zoneReached[startIndex] = inStart && zoneNodes[startIndex] > 0;
                rows.Add(new ValidateRow
                {
                    check = $"zone {startZone} (start)", pass = startIndex >= 0 && inStart && zoneNodes[startIndex] > 0,
                    detail = startIndex < 0 ? $"data.startZone '{startZone}' is not a zone id"
                        : $"{zoneNodes[startIndex]} grid nodes, {zoneGraphNodes[startIndex]} graph nodes; the player spawn's grid node is {(inStart ? "in it" : start >= 0 ? $"tagged {g.tag[start]}, not in it" : "missing")}",
                });
                var order = new List<int>();
                for (int i = 0; i < zoneIds.Count; i++) if (i != startIndex) order.Add(i);
                order.Sort((a, b) => zoneCost[a] != zoneCost[b] ? zoneCost[a].CompareTo(zoneCost[b]) : a.CompareTo(b));
                var open = new bool[zoneIds.Count];
                if (startIndex >= 0) open[startIndex] = true;
                var opened = new List<string> { startZone };
                foreach (int zi in order)
                {
                    int touched = 0, gridTouched = 0;
                    Func<int, bool> allowed(int[] tags) => n => tags[n] < 0 || (tags[n] < open.Length && open[tags[n]]) || tags[n] == zi;
                    if (graph != null && startG >= 0)
                    {
                        bool[] seen = GraphReach(graph, startG, false, allowed(graphTag));
                        for (int n = 0; n < seen.Length; n++) if (seen[n] && graphTag[n] == zi) touched++;
                    }
                    if (start >= 0)
                    {
                        bool[] seen = GridReach(g, start, false, allowed(g.tag));
                        for (int n = 0; n < g.count; n++) if (seen[n] && g.tag[n] == zi) gridTouched++;
                    }
                    bool pass = graph != null ? touched > 0 : gridTouched > 0;
                    zoneReached[zi] = pass;
                    rows.Add(new ValidateRow
                    {
                        check = $"zone {zoneIds[zi]} (cost {F(zoneCost[zi])})", pass = pass,
                        detail = (pass ? $"reached from the spawn through {string.Join(", ", opened)} only" : $"not reached while only {string.Join(", ", opened)} are open")
                            + $": the player's graph reaches {touched} of its {zoneGraphNodes[zi]} graph nodes; the enemies' grid {gridTouched} of its {zoneNodes[zi]} grid nodes",
                    });
                    open[zi] = true;
                    opened.Add(zoneIds[zi]);
                }
            }

            // --- spots: the player's time on the graph (all zones open), the enemies' on the grid ---
            var spots = Spots(cfg, map, data);
            var gridScratch = new Skygrind.Core.Flow.PathScratch();
            var path = new NavPath();
            int r = (int)Math.Ceiling(reach / g.cell);
            var spotNodes = new List<int>();
            foreach (ValidateSpot s in spots)
            {
                int node = GridSpotNode(g, s.x, s.y, s.z, r, reach, reachHeight);
                spotNodes.Add(node);
                string enemies = node < 0 ? "enemies' grid: no node within reach"
                    : start >= 0 && Skygrind.Core.Flow.GridPath(g, start, node, true, g.count + 1, gridScratch) != null ? $"enemies' grid: {F(gridScratch.cost / walkSpeed)} s"
                    : "enemies' grid: no path (player-only)";
                if (graph == null || startG < 0)
                {
                    rows.Add(VerbRule(new ValidateRow { check = s.label, pass = node >= 0 && enemies.EndsWith(" s"), detail = $"{P(s.x, s.y, s.z)}: {enemies}" }, s, sm, zoneIds, zoneReached, graph, graphAcross));
                    continue;
                }
                int gn = GraphSpotNode(graph, s, graphAcross, reachHeight, out double away);
                if (gn < 0)
                {
                    rows.Add(VerbRule(new ValidateRow { check = s.label, pass = false, detail = $"{P(s.x, s.y, s.z)}: no graph node within {F(graphAcross)} m across and {F(reachHeight)} m in height; {enemies}; {Nearby(g, map, data, s)}" }, s, sm, zoneIds, zoneReached, graph, graphAcross));
                    continue;
                }
                bool found = Astar.Path(graph, startG, gn, heuristicSpeed, path);
                rows.Add(VerbRule(new ValidateRow
                {
                    check = s.label, pass = found,
                    detail = found
                        ? $"{P(s.x, s.y, s.z)}: {F(path.cost)} s from the spawn ({Kinds(path)}; the last node {F(away)} m from it); {enemies}"
                        : $"{P(s.x, s.y, s.z)}: graph node {gn} has no path from the spawn; {enemies}; {Nearby(g, map, data, s)}",
                }, s, sm, zoneIds, zoneReached, graph, graphAcross));
            }

            // --- pads land on walkable ground (the grid) ---
            if (L(Get(data, "pads") ?? Get(map, "pads")) is List<object> pads)
                for (int i = 0; i < pads.Count; i++)
                {
                    var d = O(pads[i]);
                    double px = N(d["x"]), py = N(d["y"]), pz = N(d["z"]);
                    int padNode = g.NodeAt(px, py, pz, lookBelow, lookAbove);
                    if (Get(d, "target") is Dictionary<string, object> tg)
                    {
                        double tx = N(tg["x"]), ty = N(tg["y"]), tz = N(tg["z"]);
                        int land = LandingNode(g, tx, ty, tz, out double dy);
                        rows.Add(new ValidateRow
                        {
                            check = $"pad {i}", pass = padNode >= 0 && land >= 0,
                            detail = $"{P(px, py, pz)} {(padNode >= 0 ? "on grid node " + padNode : "OFF the grid")}; aimed at {P(tx, ty, tz)}: "
                                + (land >= 0 ? $"lands on grid node {land} (y {F(g.y[land])})" : double.IsInfinity(dy) ? "no grid node within a cell" : $"the nearest grid node within a cell is {F(dy)} m off in height (tolerance {F(UnityTuning.MapPadLandTolerance)} m, UnityTuning.MapPadLandTolerance)"),
                        });
                    }
                    else rows.Add(new ValidateRow { check = $"pad {i}", pass = padNode >= 0, detail = $"{P(px, py, pz)} {(padNode >= 0 ? "on grid node " + padNode : "OFF the grid")}; plain (straight up)" });
                }

            // --- spawn nodes per zone: SURVIVAL's own (Zones samples them at load: config zones.nodeSpacing, a husk capsule
            // fits, tagged by zone; enemies spawn only on nodes in open zones), on a fresh world of the map ---
            var spawnNodes = new List<(int node, bool high)>();
            if (sm != null && sm.zoneParts.Count > 0)
            {
                var zones = new Zones(cfg, sm, new GameWorld(sm.BuildOctree(), sm.CreateCore(cfg.movement)), new EventBus());
                var ground = new int[zoneIds.Count];
                var high = new int[zoneIds.Count];
                int offGridNodes = 0;
                foreach (SpawnNode s in zones.nodes)
                {
                    if (s.zone >= 0 && s.zone < ground.Length)
                    {
                        if (s.high) high[s.zone]++;
                        else ground[s.zone]++;
                    }
                    int n = g.NodeAt(s.x, s.y, s.z, lookBelow, lookAbove);
                    if (n < 0) offGridNodes++;
                    else spawnNodes.Add((n, s.high));
                }
                for (int i = 0; i < zoneIds.Count; i++)
                    rows.Add(new ValidateRow
                    {
                        check = $"spawn nodes in zone {zoneIds[i]}", pass = ground[i] + high[i] >= UnityTuning.MapMinSpawnsPerZone,
                        detail = $"{ground[i] + high[i]} spawn nodes ({ground[i]} ground, {high[i]} high: y >= config zones.highNodeMin; minimum {UnityTuning.MapMinSpawnsPerZone}, UnityTuning.MapMinSpawnsPerZone)",
                    });
                rows.Add(new ValidateRow
                {
                    check = "spawn nodes on the grid", pass = true,
                    detail = $"{zones.nodes.Count} spawn nodes, {zones.nodes.Count - offGridNodes} on a grid node, {offGridNodes} on none (a husk capsule fits where the grid's probe doesn't)",
                });
            }
            else rows.Add(new ValidateRow { check = "spawn nodes", pass = zoneIds.Count == 0, detail = "no zone parts: SURVIVAL's spawn nodes (Zones) can't be sampled on this map" });

            // --- the map's own spawn lists (data.spawns: only the enemy bench reads them in the Unity game; SURVIVAL doesn't) ---
            var spawns = O(Get(data, "spawns")) ?? O(Get(map, "spawns"));
            var perZone = new int[zoneIds.Count];
            int untagged = 0, offGrid = 0, total = 0;
            var offList = new List<string>();
            foreach (string kind in new[] { "ground", "high" })
                if (L(Get(spawns, kind)) is List<object> list)
                    foreach (object o in list)
                    {
                        var d = O(o);
                        double x = N(d["x"]), y = N(d["y"]), z = N(d["z"]);
                        total++;
                        int n = g.NodeAt(x, y, z, lookBelow, lookAbove);
                        if (n < 0)
                        {
                            offGrid++;
                            offList.Add($"{kind} {P(x, y, z)}");
                            continue;
                        }
                        if (g.tag[n] < 0 || g.tag[n] >= perZone.Length) untagged++;
                        else perZone[g.tag[n]]++;
                    }
            var zoneCounts = new List<string>();
            for (int i = 0; i < zoneIds.Count; i++) zoneCounts.Add($"{zoneIds[i]} {perZone[i]}");
            if (untagged > 0) zoneCounts.Add($"no zone {untagged}");
            rows.Add(new ValidateRow
            {
                check = "map spawn lists", pass = true,
                detail = $"{total} (ground + high; read by the enemy bench only, not by SURVIVAL); per zone: {string.Join(", ", zoneCounts)}; "
                    + (offGrid == 0 ? "each on a grid node" : $"{offGrid} on no grid node (within {F(lookBelow)} m below / {F(lookAbove)} m above): {string.Join("; ", offList)}"),
            });

            // --- islands: grid components with no grid way back to the spawn, and whether the player's graph leaves them ---
            if (start >= 0)
            {
                bool[] back = GridReach(g, start, true, n => true);
                bool[] forward = GridReach(g, start, false, n => true);
                int unreached = 0;
                for (int n = 0; n < g.count; n++) if (!forward[n]) unreached++;
                var holder = new Dictionary<int, List<string>>();
                for (int i = 0; i < spots.Count; i++)
                {
                    if (spotNodes[i] < 0) continue;
                    if (!holder.TryGetValue(spotNodes[i], out List<string> l)) holder[spotNodes[i]] = l = new List<string>();
                    l.Add(spots[i].label);
                }
                var spawnAt = new Dictionary<int, int>();
                foreach ((int node, bool _) in spawnNodes) spawnAt[node] = spawnAt.TryGetValue(node, out int c) ? c + 1 : 1;
                bool[] graphBack = graph != null && startG >= 0 ? GraphReach(graph, startG, true, n => true) : null;
                var gridToGraph = new Dictionary<int, List<int>>();
                if (graphBack != null)
                    for (int j = 0; j < graph.nodes.Count; j++)
                    {
                        NavNode n = graph.nodes[j];
                        int gn = g.NodeAt(n.x, n.y, n.z, lookBelow, lookAbove);
                        if (gn < 0) continue;
                        if (!gridToGraph.TryGetValue(gn, out List<int> l)) gridToGraph[gn] = l = new List<int>();
                        l.Add(j);
                    }
                Islands(g, back, holder, spawnAt, gridToGraph, graphBack, cfg.Num("ai.grid.step"), rows);
                rows.Add(new ValidateRow { check = "grid reach", pass = true, detail = $"{unreached} of {g.count} grid nodes are out of the spawn's forward reach on the enemies' grid" });
            }

            // --- the kill plane and the bounds ---
            float minY = float.PositiveInfinity;
            for (int n = 0; n < g.count; n++) minY = Math.Min(minY, g.y[n]);
            rows.Add(new ValidateRow
            {
                check = "kill plane", pass = g.count > 0 && minY > killPlaneY,
                detail = $"killPlaneY {F(killPlaneY)}; the lowest walkable grid node is at y {F(minY)}",
            });
            double half = floorSize / 2;
            var outside = new List<string>();
            var low = new List<string>();
            foreach (ValidateSpot s in spots) Bounds(s, half, killPlaneY, outside, low);
            if (L(Get(data, "pads") ?? Get(map, "pads")) is List<object> padList)
                for (int i = 0; i < padList.Count; i++)
                {
                    var d = O(padList[i]);
                    Bounds(new ValidateSpot { label = $"pad {i}", x = N(d["x"]), y = N(d["y"]), z = N(d["z"]) }, half, killPlaneY, outside, low);
                    if (Get(d, "target") is Dictionary<string, object> tg) Bounds(new ValidateSpot { label = $"pad {i} target", x = N(tg["x"]), y = N(tg["y"]), z = N(tg["z"]) }, half, killPlaneY, outside, low);
                }
            foreach (string kind in new[] { "ground", "high" })
                if (L(Get(spawns, kind)) is List<object> list)
                    for (int i = 0; i < list.Count; i++)
                    {
                        var d = O(list[i]);
                        Bounds(new ValidateSpot { label = $"{kind} spawn {i}", x = N(d["x"]), y = N(d["y"]), z = N(d["z"]) }, half, killPlaneY, outside, low);
                    }
            if (L(Get(data, "grappleNodes") ?? Get(map, "grappleNodes")) is List<object> nodes)
                for (int i = 0; i < nodes.Count; i++)
                {
                    var d = O(nodes[i]);
                    Bounds(new ValidateSpot { label = $"grapple node {i}", x = N(d["x"]), y = N(d["y"]), z = N(d["z"]) }, half, killPlaneY, outside, low);
                }
            rows.Add(new ValidateRow
            {
                check = "above the kill plane", pass = low.Count == 0,
                detail = low.Count == 0 ? "every spawn, spot, pad, pad target and grapple node is above killPlaneY" : string.Join("; ", low),
            });
            rows.Add(new ValidateRow
            {
                check = "inside the floor square", pass = outside.Count == 0,
                detail = outside.Count == 0
                    ? $"every spawn, spot, pad, pad target and grapple node is within +-{F(half)} m (floorSize {F(floorSize)}: the nav grid's square)"
                    : $"outside +-{F(half)} m (the nav grid can't see them): {string.Join("; ", outside)}",
            });
            double gridEnd = g.origin + g.size * g.cell;
            rows.Add(new ValidateRow
            {
                check = "nav grid square", pass = g.origin <= -half && gridEnd >= half,
                detail = $"the grid spans {F(g.origin)} .. {F(gridEnd)} m; the floor square +-{F(half)} m",
            });
            BoxExtents(map, half, rows);
            return Finish(head, rows);
        }

        static string Kinds(NavPath path)
        {
            var counts = new Dictionary<string, int>();
            var order = new List<string>();
            foreach (string k in path.kinds)
            {
                if (!counts.ContainsKey(k))
                {
                    counts[k] = 0;
                    order.Add(k);
                }
                counts[k]++;
            }
            if (order.Count == 0) return "at the spawn";
            var parts = new List<string>();
            foreach (string k in order) parts.Add(counts[k] > 1 ? $"{k} x{counts[k]}" : k);
            return string.Join(", ", parts);
        }

        static void Bounds(ValidateSpot s, double half, double killPlaneY, List<string> outside, List<string> low)
        {
            if (Math.Abs(s.x) > half || Math.Abs(s.z) > half) outside.Add($"{s.label} {P(s.x, s.y, s.z)}");
            if (!(s.y > killPlaneY)) low.Add($"{s.label} {P(s.x, s.y, s.z)} is not above killPlaneY {F(killPlaneY)}");
        }

        /// <summary>The solid boxes' extent (collision.boxes, not the barriers), an information row.</summary>
        static void BoxExtents(Dictionary<string, object> map, double half, List<ValidateRow> rows)
        {
            if (!(L(Get(O(Get(map, "collision")), "boxes")) is List<object> boxes) || boxes.Count == 0) return;
            double minX = double.PositiveInfinity, maxX = double.NegativeInfinity, minZ = double.PositiveInfinity, maxZ = double.NegativeInfinity, minY = double.PositiveInfinity, maxY = double.NegativeInfinity;
            foreach (object o in boxes)
            {
                var d = O(o);
                var a = L(d["min"]);
                var b = L(d["max"]);
                minX = Math.Min(minX, N(a[0]));
                minY = Math.Min(minY, N(a[1]));
                minZ = Math.Min(minZ, N(a[2]));
                maxX = Math.Max(maxX, N(b[0]));
                maxY = Math.Max(maxY, N(b[1]));
                maxZ = Math.Max(maxZ, N(b[2]));
            }
            rows.Add(new ValidateRow
            {
                check = "solid boxes' extent", pass = true,
                detail = $"x {F(minX)} .. {F(maxX)}, y {F(minY)} .. {F(maxY)}, z {F(minZ)} .. {F(maxZ)} ({boxes.Count} collision boxes; walls may stand outside the +-{F(half)} m floor square: the grid sees no floor there)",
            });
        }

        static (string, int) Finish(StringBuilder head, List<ValidateRow> rows)
        {
            int findings = 0, verbs = 0;
            foreach (ValidateRow r in rows)
            {
                if (!r.pass) findings++;
                else if (r.verb) verbs++;
            }
            var sb = new StringBuilder(head.ToString());
            if (verbs > 0) // a map without verb gates (the web's) keeps its report as it was
                sb.Append($"- VERB: a spot the player's graph can't reach that carries a designed verb gate (its \"verb\": one of {string.Join(", ", UnityTuning.MapVerbs)}) in a zone that is reached; not a finding.\n");
            sb.Append($"\n**findings: {findings}** ({rows.Count} checks{(verbs > 0 ? $", {verbs} VERB" : "")})\n\n| check | result | numbers |\n|---|---|---|\n");
            foreach (ValidateRow r in rows) sb.Append($"| {r.check} | {(!r.pass ? "FINDING" : r.verb ? "VERB" : "PASS")} | {r.detail.Replace("|", "/")} |\n");
            return (sb.ToString(), findings);
        }

        /// <summary>
        /// A spot row through the verb rule (the lead, NIGHT15): a spot the player's graph can't reach that carries a known
        /// verb (UnityTuning.MapVerbs) is VERB, not a FINDING, while its zone (survival/zones.js tagAt: the zone at y + 1)
        /// is reached; an unknown verb, a spot in no zone or in a zone not reached stays a FINDING. A spot without a verb,
        /// or one the graph reaches, keeps its row (the verb noted).
        /// </summary>
        static ValidateRow VerbRule(ValidateRow row, ValidateSpot s, SurvivalMap sm, List<string> zoneIds, bool[] zoneReached, NavGraph graph, double across)
        {
            if (string.IsNullOrEmpty(s.verb)) return row;
            if (row.pass)
            {
                row.detail += $"; verb {s.verb} (the graph reaches it too)";
                return row;
            }
            if (Array.IndexOf(UnityTuning.MapVerbs, s.verb) < 0)
            {
                row.detail = $"verb '{s.verb}' is none of {string.Join(", ", UnityTuning.MapVerbs)}; " + row.detail;
                return row;
            }
            int zi = sm != null && sm.zoneParts.Count > 0 ? ZoneMath.ZoneIndexAt(sm.zoneParts, s.x, s.y + 1, s.z) : -1;
            if (zi < 0 || zi >= zoneIds.Count)
            {
                row.detail = $"by design reached by {s.verb}, but it stands in no zone (a verb spot must sit in a zone the player reaches); " + row.detail;
                return row;
            }
            if (!zoneReached[zi])
            {
                row.detail = $"by design reached by {s.verb}, but its zone {zoneIds[zi]} is not reached; " + row.detail;
                return row;
            }
            row.pass = true;
            row.verb = true;
            row.detail = $"by design: reached by {s.verb}; RIVAL's graph has no {s.verb} ({GraphUnder(graph, s, across)}); zone {zoneIds[zi]} is reached; " + row.detail;
            return row;
        }

        /// <summary>The highest graph node under a spot within `across` m horizontally: how far below it the graph stands.</summary>
        static string GraphUnder(NavGraph graph, ValidateSpot s, double across)
        {
            if (graph == null) return "no player's graph";
            double best = double.NegativeInfinity;
            foreach (NavNode n in graph.nodes)
            {
                double dx = n.x - s.x, dz = n.z - s.z;
                if (dx * dx + dz * dz <= across * across && n.y <= s.y + 0.5 && n.y > best) best = n.y;
            }
            return double.IsNegativeInfinity(best) ? $"no graph node under it within {F(across)} m across" : $"the highest graph node under it within {F(across)} m across is {F(s.y - best)} m below";
        }

        /// <summary>Writes Reports/MAP-&lt;id&gt;-validate.md under repoRoot; returns its path and the findings.</summary>
        public static (string path, int findings) Write(GameConfig cfg, Dictionary<string, object> map, string repoRoot, string label = null)
        {
            (string md, int findings) = Run(cfg, map, label);
            string id = Get(map, "name") as string ?? "map";
            string dir = Path.Combine(repoRoot, UnityTuning.MapReportDir);
            Directory.CreateDirectory(dir);
            string path = Path.Combine(dir, $"MAP-{id}-validate.md");
            File.WriteAllText(path, md, new UTF8Encoding(false));
            return (path, findings);
        }

